# เริ่มต้น
print("เริ่มต้น")

# ไปสนามกีฬา
print("ไปสนามกีฬา")

# กำหนดตัวแปรสำหรับนับจำนวนรอบที่วิ่งได้จริงตอนแรกเป็น 0 รอบ
round_count = 0

# วนซ้ำ (Loop) ตราบใดที่ยังวิ่งไม่ครบ 3 รอบ
while round_count < 3:
    # วิ่งรอบสนาม
    print("วิ่งรอบสนาม")
    
    # เพิ่มจำนวนรอบที่วิ่งได้ทีละ 1 รอบ
    round_count += 1
    print(f"-> วิ่งไปแล้ว {round_count} รอบ")
    
    # เงื่อนไขการตรวจสอบ: วิ่งครบ 3 รอบหรือยัง?
    if round_count == 3:
        print("ตรวจสอบเงื่อนไข: วิ่งครบ 3 รอบแล้ว (ใช่)")
    else:
        print("ตรวจสอบเงื่อนไข: ยังไม่ครบ 3 รอบ (ไม่ใช่) -> กลับไปวิ่งใหม่")

# กลับบ้าน
print("กลับบ้าน")

