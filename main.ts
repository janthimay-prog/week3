//  กำหนดตัวแปรสำหรับนับจำนวนรอบที่วิ่งได้จริงตอนแรกเป็น 0 รอบ
let round_count = 0
//  วนซ้ำ (Loop) ตราบใดที่ยังวิ่งไม่ครบ 3 รอบ
while (round_count < 3) {
    //  วิ่งรอบสนาม
    console.log("วิ่งรอบสนาม")
    //  เพิ่มจำนวนรอบที่วิ่งได้ทีละ 1 รอบ
    round_count += 1
    console.log("-> วิ่งไปแล้ว {round_count} รอบ")
    //  เงื่อนไขการตรวจสอบ: วิ่งครบ 3 รอบหรือยัง?
    if (round_count == 3) {
        console.log("ตรวจสอบเงื่อนไข: วิ่งครบ 3 รอบแล้ว (ใช่)")
    } else {
        console.log("ตรวจสอบเงื่อนไข: ยังไม่ครบ 3 รอบ (ไม่ใช่) -> กลับไปวิ่งใหม่")
    }
    
}
